# 지도 여백(위도·경도 범위)
LAT_RANGE = (33.0, 38.7)
LNG_RANGE = (125.8, 129.7)
MEAN_LAT_COS = cos(radians(36.0))


def locate(address: str | None) -> tuple[float, float] | None:
    """주소에서 대표 좌표를 찾는다.

    시·도를 먼저 확정한 뒤 그 안에서 시·군·구를 찾는다. '광주광역시 광산구'와
    '경기도 광주시'처럼 이름이 겹치는 곳을 섞지 않기 위한 순서다.
    """
    if not address:
        return None
    tokens = address.split()
    if not tokens:
        return None

    province = PROVINCE_ALIASES.get(tokens[0])
    if province is None:
        # 시·도를 생략한 주소('구미시 1공단로 …')도 받아준다.
        for (prov, city), point in CITIES.items():
            if tokens[0].startswith(city):
                return point
        return None

    for token in tokens[1:3]:
        name = token.rstrip("시군구")
        point = CITIES.get((province, name))
        if point:
            return point
    return PROVINCES.get(province)


def project(lat: float, lng: float, width: float, height: float) -> tuple[float, float]:
    """위경도를 SVG 좌표로. 한국 범위에서는 경도만 cos(위도)로 눌러주면 충분하다."""
    lat_span = LAT_RANGE[1] - LAT_RANGE[0]
    lng_span = (LNG_RANGE[1] - LNG_RANGE[0]) * MEAN_LAT_COS
    x = (lng - LNG_RANGE[0]) * MEAN_LAT_COS / lng_span * width
    y = (LAT_RANGE[1] - lat) / lat_span * height
    return round(x, 1), round(y, 1)


def outline_paths(width: float, height: float) -> list[str]:
    """지도 배경 폴리곤들의 SVG points 문자열."""
    paths = []
    for shape in (MAINLAND, JEJU):
        points = [project(lat, lng, width, height) for lat, lng in shape]
        paths.append(" ".join(f"{x},{y}" for x, y in points))
    return paths
